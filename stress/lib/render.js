// Renders report/results.json into SCORECARD.md (Markdown first) and scorecard.svg (one bar per check:
// seeds found, seeds missed, false alarms). No dependencies: the SVG is written by hand.
const fs = require('fs')
const path = require('path')

const esc = s => String(s ?? '').replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
const cell = s => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ')

function perCheck(results) {
  const C = {}
  const c = k => (C[k] ||= { check: k, seeds: 0, hits: 0, misses: [], fpControl: [], fpVariant: [] })
  for (const s of results.seeds) for (const e of s.expect || []) {
    const k = e.check || `gap:${e.gap}`
    c(k).seeds++
    if (e.hit) c(k).hits++; else c(k).misses.push(s.id)
  }
  for (const s of results.seeds) for (const n of [...(s.noise || []), ...(s.forbidden || [])]) c(n.check).fpVariant.push(`${s.id}: ${n.title}`)
  for (const b of results.bases) for (const a of b.alarms.filter(a => !a.accepted)) c(a.check).fpControl.push(`${b.base}: ${a.title}`)
  return Object.values(C).sort((a, b) => (b.seeds - a.seeds) || a.check.localeCompare(b.check))
}

function svg(rows) {
  const W = 760, rowH = 22, left = 250, top = 40, scale = 22
  const H = top + rows.length * rowH + 40
  const out = [`<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}" font-family="system-ui, sans-serif" font-size="12">`,
    `<rect width="${W}" height="${H}" fill="#fff"/>`,
    `<text x="12" y="20" font-size="14" font-weight="600">Seeded bugs per check: found, missed, false alarms</text>`,
    `<g transform="translate(${left + 4},28)"><rect width="10" height="10" fill="#188038"/><text x="14" y="9">found</text><rect x="70" width="10" height="10" fill="#d93025"/><text x="84" y="9">missed</text><rect x="150" width="10" height="10" fill="#f29900"/><text x="164" y="9">false alarm</text></g>`]
  rows.forEach((r, i) => {
    const y = top + i * rowH + 6
    out.push(`<text x="${left - 6}" y="${y + 12}" text-anchor="end">${esc(r.check.length > 38 ? r.check.slice(0, 37) + '…' : r.check)}</text>`)
    let x = left
    for (const [n, col] of [[r.hits, '#188038'], [r.misses.length, '#d93025'], [r.fpControl.length + r.fpVariant.length, '#f29900']]) {
      if (!n) continue
      out.push(`<rect x="${x}" y="${y}" width="${n * scale - 2}" height="${rowH - 6}" fill="${col}" rx="2"/><text x="${x + 4}" y="${y + 12}" fill="#fff" font-size="11">${n}</text>`)
      x += n * scale
    }
  })
  out.push('</svg>')
  return out.join('\n')
}

// seeds counted clean (found or understood, nothing forbidden, no noise) in results-main.json vs now
const clean = s => s && !s.error && s.detected && !(s.forbidden || []).length && !(s.noise || []).length
function beforeAfter(results, dir) {
  const f = path.join(dir, 'results-main.json')
  if (!fs.existsSync(f)) return []
  const old = new Map(JSON.parse(fs.readFileSync(f, 'utf8')).seeds.map(s => [s.id, s]))
  const cats = {}
  for (const s of results.seeds) {
    if (s.detectable === false) continue
    const c = cats[s.category || 'other'] ||= { cat: s.category || 'other', n: 0, before: 0, after: 0 }
    c.n++; if (clean(old.get(s.id))) c.before++; if (clean(s)) c.after++
  }
  const rows = Object.values(cats)
  rows.push(rows.reduce((t, r) => ({ cat: '**all**', n: t.n + r.n, before: t.before + r.before, after: t.after + r.after }), { n: 0, before: 0, after: 0 }))
  return rows
}

function render(results, dir) {
  const rows = perCheck(results)
  const seeds = results.seeds.filter(s => !s.error)
  const det = seeds.filter(s => s.detectable !== false && s.checks.length)
  const quiet = seeds.filter(s => !s.checks.length), understood = quiet.filter(s => s.detected && !(s.forbidden || []).length && !(s.noise || []).length)
  const found = det.filter(s => s.detected)
  const invalid = [...results.bases.filter(b => b.valid && !b.valid.ok).map(b => `base ${b.base}`), ...results.seeds.filter(s => s.error || (s.valid && !s.valid.ok)).map(s => s.id)]
  const proofs = seeds.filter(s => s.hasProof && !s.probe && s.checks.length), proofOk = proofs.filter(s => s.negative?.failsOnBase && s.valid?.ok)
  const fpControl = results.bases.flatMap(b => b.alarms.filter(a => !a.accepted)), noisy = seeds.filter(s => (s.noise || []).length || (s.forbidden || []).length)
  const byCat = {}
  for (const s of det) { const c = byCat[s.category || 'other'] ||= { n: 0, hit: 0 }; c.n++; if (s.detected) c.hit++ }
  const md = []
  md.push('# Stress corpus scorecard', '')
  md.push(`Generated by \`node stress/bin/stress.js run\` on ${results.at.slice(0, 16).replace('T', ' ')} UTC (${results.seconds}s). Method: [README.md](../README.md).`, '')
  md.push('![scorecard](scorecard.svg)', '')
  md.push('## Summary', '')
  md.push('| Measure | Value |', '| --- | --- |')
  md.push(`| Seeded bugs found | **${found.length} of ${det.length}** (${det.length ? Math.round(found.length / det.length * 100) : 0}%) |`)
  md.push(`| Bug-free variants understood (shapes, configs, probes) | **${understood.length} of ${quiet.length}** (graph as expected, no new alarm) |`)
  md.push(`| By category | ${Object.entries(byCat).map(([k, v]) => `${k} ${v.hit}/${v.n}`).join(' · ')} |`)
  md.push(`| False alarms on clean apps | ${fpControl.length} (in ${results.bases.length} control apps) |`)
  md.push(`| Seeds with extra alarms (noise) | ${noisy.length} |`)
  md.push(`| Cases proven valid | ${results.bases.length + seeds.length - invalid.length} of ${results.bases.length + results.seeds.length}${invalid.length ? ` (invalid: ${invalid.join(', ')})` : ''} |`)
  md.push(`| Bugs proven real at runtime | ${proofOk.length} of ${proofs.length} seeds with a proof test (passes on the seeded app, fails on the clean one) |`)
  md.push('')
  const before = beforeAfter(results, dir)
  if (before.length) {
    md.push('## Before and after this round of fixes', '')
    md.push('The same seeds scored with the toolkit of `main` before the fixes (`report/results-main.json`). A seed counts when its bug is found (or a bug-free variant is understood) with no false alarm.', '')
    md.push('| Category | Seeds | Before | After |', '| --- | ---: | ---: | ---: |')
    for (const r of before) md.push(`| ${r.cat} | ${r.n} | ${r.before} | ${r.after} |`)
    md.push('')
  }
  md.push('## Per check', '')
  md.push('Recall = seeds found / seeds that expect the check. False alarms count alarms on clean control apps plus unexpected new alarms in seeded variants.', '')
  md.push('| Check | Seeds | Found | Missed | Recall | False alarms | Missed seeds |', '| --- | ---: | ---: | ---: | ---: | ---: | --- |')
  for (const r of rows) md.push(`| \`${r.check}\` | ${r.seeds} | ${r.hits} | ${r.misses.length} | ${r.seeds ? Math.round(r.hits / r.seeds * 100) + '%' : '–'} | ${r.fpControl.length + r.fpVariant.length} | ${r.misses.join(', ')} |`)
  md.push('')
  md.push('## Seeds', '')
  md.push('| Seed | Category | Planted bug | Expected checks | Result | Extra alarms | Proof |', '| --- | --- | --- | --- | --- | --- | --- |')
  for (const s of results.seeds) {
    const res = s.error ? `error: ${cell(s.error)}` : s.probe && s.discover?.ok ? (s.forbidden?.length || s.noise?.length ? '❌ false alarm' : '✅ quiet') : s.error ? `error: ${cell(s.error)}` : !s.discover?.ok ? `pipeline failed (${s.discover?.step})` : !s.checks.length ? (s.detected && !(s.forbidden || []).length && !(s.noise || []).length ? '✅ understood' : `❌ ${[...(s.graph || []).filter(g => !g.hit).map(g => `graph ${g.rel || g.type} ${g.to || g.id || ''}`), ...((s.forbidden || []).length || (s.noise || []).length ? ['false alarm'] : [])].join(', ')}`) : s.detected ? '✅ found' : s.detectable === false ? '➖ out of reach' : `❌ missed ${[...(s.expect || []).filter(e => !e.hit).map(e => e.check || 'gap:' + e.gap), ...(s.graph || []).filter(g => !g.hit).map(g => `graph ${g.rel || g.type}${g.to ? ' ' + g.to : ''}`)].join(', ')}`
    const proof = !s.hasProof ? 'smoke' : !s.checks.length && !s.probe ? (s.valid?.ok ? '✅ same behaviour' : '❌') : s.probe ? (s.valid?.ok ? '✅ behaves as claimed' : '❌') : s.valid?.ok && s.negative?.failsOnBase ? '✅' : s.valid && !s.valid.ok ? '❌ seeded app invalid' : s.negative && !s.negative.failsOnBase ? '⚠️ passes on base' : '?'
    md.push(`| ${s.id} | ${s.category || ''} | ${cell(s.bug || s.title)} | ${s.checks.map(c => `\`${c}\``).join(' ')} | ${res} | ${[...(s.noise || []), ...(s.forbidden || [])].map(n => `\`${n.check}\` ${cell(n.title)}`).join('; ')} | ${proof} |`)
  }
  md.push('')
  md.push('## Clean control apps', '')
  for (const b of results.bases) {
    md.push(`### ${b.base}${b.title ? `: ${b.title}` : ''}`, '')
    md.push(`Valid: ${b.valid ? (b.valid.ok ? `yes (compile, ${b.valid.tests.pass} tests${b.valid.ts ? ', tsc' : ''}${b.valid.ui5.length ? `, UI5 lint + build ×${b.valid.ui5.length}` : ''})` : `**no**: ${cell(JSON.stringify(b.valid).slice(0, 300))}`) : 'not checked'} · ${b.findings} findings · ${b.alarms.filter(a => !a.accepted).length} false alarms`, '')
    if (b.alarms.length) {
      md.push('| Alarm | Check | Evidence | Verdict |', '| --- | --- | --- | --- |')
      for (const a of b.alarms) md.push(`| ${cell(a.title)} | \`${a.check}\` | ${a.evidence ? `${a.evidence.file}:${a.evidence.line}` : ''} | ${a.accepted ? `accepted: ${cell(a.accepted)}` : '**false alarm**'} |`)
      md.push('')
    }
  }
  if (invalid.length) {
    md.push('## Invalid cases', '')
    for (const s of results.seeds.filter(s => s.error || (s.valid && !s.valid.ok))) md.push(`- **${s.id}**: ${cell(s.error || JSON.stringify({ compile: s.valid.compile.log, tests: s.valid.tests.log, ts: s.valid.ts?.log, ui5: s.valid.ui5.filter(u => !u.ok) }).slice(0, 600))}`)
    md.push('')
  }
  fs.writeFileSync(path.join(dir, 'SCORECARD.md'), md.join('\n'))
  fs.writeFileSync(path.join(dir, 'scorecard.svg'), svg(rows))
}

module.exports = { render, perCheck }
