// Writes the UI test cases as an OPA5 journey with the Fiori elements test library (sap.fe.test),
// the same API SAP's own Fiori elements samples use. Files go to <webapp>/test/discovery/ in the app:
//   uitests.qunit.html   test page (loads UI5 from the app's own bootstrap URL)
//   uitests.qunit.js     one opaTest per visit; each case ends with a marker assertion "[UIT:…]"
// The runner (run.js) maps the markers back to the cases. When a check fails, OPA stops that visit,
// so later cases of the same visit are reported as "not run".
const q = s => JSON.stringify(s)

function html(app) {
  // the app's bootstrap may be relative (resources/sap-ui-core.js); the page sits two folders deeper
  const boot = /^(https?:)?\/\//.test(app.bootstrap || '') ? app.bootstrap : app.bootstrap ? `../../${app.bootstrap.replace(/^\.\//, '')}` : '../../resources/sap-ui-core.js'
  const res = boot.replace(/sap-ui-core\.js.*$/, '')
  return `<!DOCTYPE html>
<html lang="en">
<!-- Generated by cap-discovery-toolkit (addon uitests). UI promises from the annotations, checked in the running app. -->
<head>
  <meta charset="UTF-8">
  <title>UI promises (generated)</title>
  <script id="sap-ui-bootstrap" src="${boot}"
    data-sap-ui-theme="sap_horizon" data-sap-ui-animation="false" data-sap-ui-compatVersion="edge" data-sap-ui-async="true"
    data-sap-ui-resourceroots='{ ${q(app.id)}: "../../" }' data-sap-ui-libs="sap.m, sap.fe.core"></script>
  <link rel="stylesheet" href="${res}sap/ui/thirdparty/qunit-2.css">
  <script src="${res}sap/ui/thirdparty/qunit-2.js"></script>
  <script src="${res}sap/ui/qunit/qunit-junit.js"></script>
  <script src="uitests.qunit.js"></script>
</head>
<body><div id="qunit"></div><div id="qunit-fixture"></div></body>
</html>
`
}

function js(app, P) {
  const visits = P.visits.filter(v => v.app === app.id)
  const byId = new Map(P.cases.map(c => [c.id, c]))
  const pages = [...new Set(visits.map(v => v.page))]
  const pageVar = id => 'on' + id.replace(/[^A-Za-z0-9]/g, '')
  const appPath = app.id.replace(/\./g, '/')
  const L = []
  const line = s => L.push(s)
  line(`// Generated by cap-discovery-toolkit (addon uitests) from the UI annotations of ${app.id}.`)
  line(`// ${P.cases.filter(c => visits.some(v => v.cases.includes(c.id))).length} cases in ${visits.length} visits. Each case states what the UI promises in one state of the record;`)
  line('// the marker assertion "[UIT:…]" after a check ties the result to its equivalence class.')
  line('/* global QUnit */')
  line(`sap.ui.require(["sap/ui/test/opaQunit", "sap/ui/test/Opa5", "sap/fe/test/JourneyRunner", "sap/fe/test/ObjectPage"], function (opaTest, Opa5, JourneyRunner, ObjectPage) {`)
  line('  "use strict"')
  line(`  const base = sap.ui.require.toUrl(${q(appPath)})`)
  line(`  // OData service of the app, resolved like the app resolves its data source`)
  line(`  const service = new URL(${q(app.dsUri || '/')}, new URL(base.endsWith("/") ? base : base + "/", location.href)).href`)
  line('  const odata = (method, path, body) => fetch(service + path, { method, credentials: "include", headers: { "content-type": "application/json", accept: "application/json" }, body: body && JSON.stringify(body) })')
  line('  // a fresh draft of the record, so the visit starts in edit mode without clicking through the UI')
  line(`  const editDraft = (set, key) => odata("DELETE", set + "(" + key.replace("IsActiveEntity=true", "IsActiveEntity=false") + ")").catch(() => null)`)
  line(`    .then(() => odata("POST", set + "(" + key + ")/" + ${q(app.service)} + ".draftEdit", { PreserveChanges: true }))`)
  line('    .then(r => { if (!r.ok) throw new Error("draftEdit " + service + set + ": HTTP " + r.status) }, e => { throw new Error("draftEdit " + service + set + ": " + e.message) })')
  line(`  const discardDraft = (set, key) => odata("DELETE", set + "(" + key.replace("IsActiveEntity=true", "IsActiveEntity=false") + ")").catch(() => null)`)
  line('  // runs fn when OPA reaches this step (not when the test is queued)')
  line('  const step = (opa, fn) => opa.waitFor({ success: () => opa.iWaitForPromise(fn()) })')
  line('  const mark = (opa, id, text) => opa.waitFor({ success: () => Opa5.assert.ok(true, "[" + id + "] " + text) })')
  line('  // Create / Delete button of a table on the page, found by the table\'s binding path (works for custom sections too)')
  line('  const tableButton = (opa, nav, button, visible) => opa.waitFor({')
  line('    controlType: "sap.ui.mdc.Table", visible: false,')
  line('    matchers: t => { const b = t.getRowBinding && t.getRowBinding(); return !!b && b.getPath().split("/").pop() === nav },')
  line('    check: ts => { const b = ts[0].findAggregatedObjects(true, c => /::StandardAction::/.test(c.getId()) && c.getId().endsWith("::StandardAction::" + button))[0]; return (!!b && b.getVisible()) === visible },')
  line('    errorMessage: "Table " + nav + ": " + button + " button should be " + (visible ? "visible" : "hidden")')
  line('  })')
  line('  // bring a section into view (the object page loads sections lazily); no-op if the facet id is not found')
  line('  const goTo = (opa, facet) => opa.waitFor({ controlType: "sap.uxap.ObjectPageLayout", success: ls => { const s = ls[0].getSections().find(s => s.getId().endsWith("::FacetSection::" + facet) || s.getId().endsWith("--" + facet)); if (s) ls[0].scrollToSection(s.getId(), 0) } })')
  line('  const fresh = (Given) => { if (new Opa5().hasAppStarted()) Given.iTearDownMyApp() }')
  line('')
  line('  const pages = {')
  for (const id of pages) { const v = visits.find(v => v.page === id); line(`    ${pageVar(id)}: new ObjectPage({ appId: ${q(app.id)}, componentId: ${q(id)}, entitySet: ${q(v.entitySet)} }),`) }
  line('  }')
  line(`  const runner = new JourneyRunner({ launchUrl: base + "/index.html", launchParameters: { "sap-language": "EN" }, opaConfig: { timeout: 20 } })`)
  line('')
  line('  runner.run({ pages }, function () {')
  line(`    QUnit.module(${q(`UI promises of ${app.id} (generated)`)})`)
  for (const v of visits) {
    const P_ = `Then.${pageVar(v.page)}`, W_ = `When.${pageVar(v.page)}`
    line('')
    line(`    opaTest(${q(`${v.id} ${v.record}, ${v.mode} mode`)}, function (Given, When, Then) {`)
    line('      fresh(Given)')
    if (v.mode === 'edit') line(`      step(Given, () => editDraft(${q(v.root.set)}, ${q(v.root.key)}))`)
    line(`      Given.iStartMyApp(${q(v.hash)})`)
    line(`      ${P_}.iSeeThisPage()${v.mode === 'edit' ? '.and.iSeeObjectPageInEditMode()' : ''}`)
    for (const id of v.cases) {
      const c = byId.get(id), k = c.check
      line(`      // ${c.id}: ${c.title} (${c.ev})`)
      if (c.kind === 'action') line(`      ${P_}.onHeader().iCheckAction({ service: ${q(k.service)}, action: ${q(k.action)} }, { enabled: ${k.enabled} })`)
      else if (c.kind === 'field' || c.kind === 'readonly') {
        let sec = null
        for (const f of k.fields) {
          if (f.section !== sec) { line(`      goTo(When, ${q(f.section)})`); sec = f.section }
          line(`      ${P_}.onForm({ section: ${q(f.section)}, fieldGroup: ${q(f.fieldGroup)} }).iCheckField({ property: ${q(f.property)} }, undefined, { editable: ${k.editable} })`)
        }
      } else line(`      tableButton(Then, ${q(k.table)}, ${q(k.button)}, ${k.visible})`)
      line(`      mark(Then, ${q(c.id)}, ${q(c.title)})`)
    }
    line('      Given.iTearDownMyApp()')
    if (v.mode === 'edit') line(`      step(Given, () => discardDraft(${q(v.root.set)}, ${q(v.root.key)}))`)
    line('    })')
  }
  line('  })')
  line('})')
  return L.join('\n') + '\n'
}

module.exports = { html, js }
