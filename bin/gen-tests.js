#!/usr/bin/env node
// Generates cds.test suites from the test design: node bin/gen-tests.js <run-dir> [out-dir]
// Only classes that carry a concrete request become code. Each one yields
//   - a characterization test that pins what the app does today (passes now), and
//   - when the design expects something else, a spec test (it.skip) to enable once fixed.
// Files are syntax-checked with node --check; they are meant to run in the app repo (jest or mocha).
const fs = require('fs')
const path = require('path')
const { execFileSync } = require('child_process')
const { loadRun } = require('../lib/load')
const { design } = require('../lib/analyse/test-design')
const { short } = require('../lib/analyse/authz')

const q = s => JSON.stringify(s)
const kind = v => v === 'success' || (+v >= 200 && +v < 300) ? 'ok' : 'err'
const okStatus = t => t === 'success' || t === 200 ? '[200, 201, 204]' : t === 'error' ? null : `[${t}]`

function main() {
  const [runDir, outArg] = process.argv.slice(2)
  if (!runDir) throw new Error('usage: gen-tests <run-dir> [out-dir]')
  const metrics = JSON.parse(fs.readFileSync(path.join(runDir, 'metrics.json'), 'utf8'))
  const { g } = loadRun(runDir)
  const td = design(g, metrics.root, { restrictAll: metrics.auth?.restrictAll })
  const out = outArg || path.join(runDir, 'tests', 'generated')
  fs.mkdirSync(out, { recursive: true })
  const userFor = (entity, action) => {
    const row = td.auth.rows.find(r => r.entity === entity && r.token === action)
    const i = row ? row.c.findIndex((c, k) => c.v === 'y' && !td.auth.users[k].anon) : -1
    return i >= 0 ? td.auth.users[i].id : (td.auth.users.find(u => !u.anon) || {}).id
  }
  const bodyFor = req => {
    const m = req.path.match(/\/(\w+)\.(\w+)$/); if (!m) return {}
    const a = g.byType('Action').find(x => x.props.name === m[2])
    return Object.fromEntries((a?.props.params || []).map(p => [p, 10]))
  }
  const files = [], counts = {}, manifest = []
  for (const c of td.categories) {
    const cls = c.classes.filter(x => x.req)
    if (!cls.length) continue
    const name = c.n.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/-$/, '')
    const suite = `${c.n} (generated)`
    const reg = (cls, kind, t) => manifest.push({ file: `${name}.test.js`, cls, kind, title: t, full: `${suite} ${t}` })
    const lines = [
      `// Generated by cap-discovery-toolkit bin/gen-tests.js from run ${metrics.run} (commit ${String(metrics.commit).slice(0, 7)}).`,
      `// Category: ${c.n} (${c.k}). ${c.why}.`,
      '// Characterization tests pin today\'s behaviour; it.skip tests state the intended behaviour.',
      "const cds = require('@sap/cds')",
      "// --with-mocks: required services without credentials run as in-process mocks, as in cds watch",
      "const { GET, POST, expect } = cds.test(__dirname + '/../..', '--with-mocks')",
      'const status = async p => { try { return (await p).status } catch (e) { return e.response?.status ?? e.status ?? e.statusCode ?? e.code } }',
      `const PW = ${JSON.stringify(Object.fromEntries(g.byType('MockUser').filter(u => u.props.password).map(u => [u.props.name, u.props.password])))} // mock-user passwords from the app config`,
      "const as = u => (u ? { auth: { username: u, password: PW[u] ?? '' } } : {})",
      '',
      `describe(${q(suite)}, () => {`]
    let n = 0
    for (const x of cls) {
      const r = x.req
      const user = x.id.startsWith('AUT:') ? x.user : userFor(r.path.includes('/') ? g.byType('ServiceEntity').find(e => r.path.includes('/' + short(e.id) + '('))?.props.name : null, r.path.split('.').pop())
      const call = r.method === 'GET' ? `GET(${q(r.path)}, as(${q(user)}))` : `POST(${q(r.path)}, ${JSON.stringify(bodyFor(r))}, as(${q(user)}))`
      const title = x.id.startsWith('AUT:') ? `${r.method} ${r.path.split('?')[0]}` : x.name
      const today = okStatus(r.today)
      const ref = `${x.id}${r.seed ? ` · seed ${r.seed}` : ''}`
      const tt = `today: ${title} as ${user || 'anonymous'} → ${today ? r.today : 'error'}`
      reg(x.id, 'today', tt)
      if (today) { lines.push(`  it(${q(tt)}, async () => {`, `    // ${ref}`, `    expect(${today}).to.include(await status(${call}))`, '  })'); n++ }
      else { lines.push(`  it(${q(tt)}, async () => {`, `    // ${ref}`, `    expect(await status(${call})).to.be.at.least(400)`, '  })'); n++ }
      if (kind(r.today) !== kind(r.status)) {
        const want = typeof r.status === 'number' && r.status >= 400 ? `expect(await status(${call})).to.be.within(400, 499)` : `expect(${okStatus(r.status)}).to.include(await status(${call}))`
        const st = `spec: ${title} as ${user || 'anonymous'} → ${String(x.expected).replace(/ \(today.*\)$/, '')}`
        reg(x.id, 'spec', st)
        lines.push(`  it.skip(${q(st)}, async () => {`, `    // ${ref} · enable once the server enforces it`, `    ${want}`, '  })'); n++
      }
    }
    lines.push('})', '')
    const f = path.join(out, `${name}.test.js`)
    fs.writeFileSync(f, lines.join('\n'))
    execFileSync(process.execPath, ['--check', f])
    files.push(path.basename(f)); counts[c.n] = n
  }
  // test title → equivalence class, read by coverage, mutation and docs addons
  fs.writeFileSync(path.join(out, 'manifest.json'), JSON.stringify({ run: metrics.run, commit: metrics.commit, tests: manifest }, null, 1))
  fs.writeFileSync(path.join(out, 'README.md'), ['# Generated cds.test suites', '', `Run ${metrics.run}, app ${metrics.app}, commit ${metrics.commit}.`, '',
    '| File | Category | Tests |', '| --- | --- | --- |', ...files.map((f, i) => `| ${f} | ${Object.keys(counts)[i]} | ${Object.values(counts)[i]} |`), '',
    'Copy the folder to `test/generated/` in the app and run it with the app\'s test runner (`npx jest test/generated` or `npx mocha test/generated`).',
    'Paths assume the folder sits two levels below the app root. `today:` tests pin current behaviour and should pass; `it.skip` `spec:` tests describe the intended behaviour and fail until the finding is fixed.',
    'Syntax-checked with `node --check`; not executed by the toolkit.', ''].join('\n'))
  console.log(`generated ${Object.values(counts).reduce((a, b) => a + b, 0)} tests in ${files.length} files → ${out} (syntax OK)`)
}

main()
